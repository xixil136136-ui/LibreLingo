    if n in number_chinese:
        return number_chinese[n]
    h = n // 100
    r = n % 100
    hc = number_chinese[h] + "百"
    if r == 0:
        return hc
    if r in number_chinese:
        return hc + number_chinese[r]
    if r > 10:
        return hc + number_chinese[r//10*10] + number_chinese[r%10]
    return hc + number_chinese[r]

